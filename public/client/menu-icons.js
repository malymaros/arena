// <svg> ikonky; veľkosť určuje CSS (.menu-ico), 1 pixel mriežky = 2 px pri 12×12
export function menuIcon(key) {
  const g = GRIDS[key], w = g[0].length, h = g.length;
  const px = g.flatMap((r, y) => [...r].map((c, x) => c === "#" ? `<rect x="${x}" y="${y}" width="1" height="1"/>` : "")).join("");
  return `<svg class="menu-ico" viewBox="0 0 ${w} ${h}" style="width:${w * 2}px;height:${h * 2}px" shape-rendering="crispEdges" aria-hidden="true">${px}</svg>`;
}
